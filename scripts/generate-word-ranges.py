"""Generate the static Unicode category table used by double-click selection.

Run with Python 3; no third-party packages. Only the generator accesses the web.
"""

from pathlib import Path
from urllib.request import urlopen

VERSION = "17.0.0"
URL = f"https://www.unicode.org/Public/{VERSION}/ucd/UnicodeData.txt"


def main():
    ranges = []
    pending = None
    with urlopen(URL) as response:
        for line in response.read().decode("utf-8").splitlines():
            code, name, category, *_ = line.split(";")
            scalar = int(code, 16)
            if name.endswith(", First>"):
                pending = scalar
                continue
            start = pending if name.endswith(", Last>") else scalar
            pending = None
            if category[0] not in "LMN" and category != "Pc":
                continue
            if ranges and ranges[-1][1] + 1 == start:
                ranges[-1] = (ranges[-1][0], scalar)
            else:
                ranges.append((start, scalar))
    output = [
        "#pragma once",
        "",
        f"// Generated by scripts/generate-word-ranges.py from Unicode {VERSION}.",
        f"// Source: {URL}",
        "// Categories L*, M*, N*, Pc; distributed under UNICODE-LICENSE.txt.",
        "#include <cstdint>",
        "",
        "namespace mempad::editor {",
        "struct ScalarRange final { std::uint32_t first; std::uint32_t last; };",
        "inline constexpr ScalarRange word_ranges[]{",
        *[f"    {{0x{start:X}U, 0x{end:X}U}}," for start, end in ranges],
        "};",
        "} // namespace mempad::editor",
        "",
    ]
    target = Path(__file__).resolve().parents[1] / "src/editor/word_ranges.h"
    target.write_text("\n".join(output), encoding="utf-8")
    print(f"Generated {len(ranges)} Unicode ranges")


if __name__ == "__main__":
    main()
